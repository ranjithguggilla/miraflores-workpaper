/** Independent structural checks on data/packet.json — the numbers the docs and CI assert. Exit 1 on any mismatch. */
import { readFileSync } from "node:fs";
import { createHash } from "node:crypto";
const file = process.argv[2] ?? "data/packet.json";
const raw = readFileSync(file);
const p = JSON.parse(raw.toString("utf8"));
const sha = createHash("sha256").update(raw).digest("hex");
const checks: [string, unknown, unknown][] = [];
const eq = (name: string, got: unknown, want: unknown) => checks.push([name, got, want]);
eq("documents", p.documents.length, 74);
eq("pages (sum page_count)", p.documents.reduce((a: number, d: any) => a + d.page_count, 0), 199);
eq("extracted_values", p.extracted_values.length, 3012);
eq("return_versions", p.return_versions.map((v: any) => v.version).join(","), "v1,v2,v3");
eq("lines per version", p.return_versions.map((v: any) => v.lines.length).join("/"), "625/625/627");
eq("lines total", p.return_versions.reduce((a: number, v: any) => a + v.lines.length, 0), 1877);
const v3 = p.return_versions[2];
eq("v3 computed_at date", v3.computed_at.slice(0, 10), "2026-06-23");
eq("v3 federal AGI", v3.summary.federal.agi, 445590);
eq("v3 federal total_tax", v3.summary.federal.total_tax, 81962);
eq("v3 federal payments", v3.summary.federal.payments, 77742);
eq("v3 federal balance_due", v3.summary.federal.balance_due, 4220);
eq("v3 california balance_due", v3.summary.california.balance_due, -8256);
const staff = Object.fromEntries(p.firm.staff.map((s: any) => [s.id, s]));
eq("st-01", `${staff["st-01"].name}/${staff["st-01"].role}`, "Priya Raman/preparer");
eq("st-02", `${staff["st-02"].name}/${staff["st-02"].role}`, "Daniel Ortiz/reviewer");
eq("st-03", `${staff["st-03"].name}/${staff["st-03"].role}`, "Helen Strand/partner");
eq("st-04 clearance", `${staff["st-04"].name}/${staff["st-04"].sensitive_data_clearance}`, "Marcus Bell/false");
eq("st-05", `${staff["st-05"].name}/${staff["st-05"].role}`, "Jo Kimura/firm_administrator");
eq("st-06", `${staff["st-06"].name}/${staff["st-06"].role}`, "Sam Adeyemi/quality_reviewer");
eq("client Erik", p.firm.client_users.some((c: any) => c.name === "Erik Lindqvist"), true);
const rules: string[] = p.firm.starter_standards.rules;
eq("rule: partner threshold 1,000", rules.some((r) => /1,000/.test(r) && /partner/i.test(r)), true);
eq("rule: no self-review", rules.some((r) => /may not review/i.test(r)), true);
eq("rule: masking + logging", rules.some((r) => /masked/i.test(r) && /logged/i.test(r)), true);
eq("rule: review notes block filing", rules.some((r) => /block filing/i.test(r)), true);
eq("timeline events", p.timeline.length, 29);
eq("v3 diagnostics", v3.diagnostics.length, 11);
let bad = 0;
for (const [n, g, w] of checks) { const ok = JSON.stringify(g) === JSON.stringify(w); if (!ok) bad++; console.log(`${ok ? "OK  " : "FAIL"} ${n}: ${JSON.stringify(g)}${ok ? "" : ` (expected ${JSON.stringify(w)})`}`); }
console.log(`sha256 ${sha}`);
console.log(bad ? `${bad} mismatches` : "packet structure verified");
process.exit(bad ? 1 : 0);
